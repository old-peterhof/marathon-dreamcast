/*
 *	dc_maple.c -- which KallistiOS subsystems start up, and one that does not.
 *
 *	CONFIRMED ON HARDWARE: with a rumble pack fitted the game never gets past the
 *	Sega licence screen; without it, it boots normally. That is long before any of
 *	our code draws anything.
 *
 *	The cause is KOS's initial bus scan, in
 *	kernel/arch/dreamcast/hardware/maple/maple_init_shutdown.c:
 *
 *	    static int maple_scan_done(maple_state_t *state) {
 *	        return state->scan_ready_mask == 0xf;
 *	    }
 *
 *	    void maple_wait_scan(void) {
 *	        thd_poll((thd_cb_t)maple_scan_done, &maple_state, 0);
 *
 *	It waits for all four ports to report. `thd_poll` with a timeout of 0 sets
 *	`wait_timeout = 0` and blocks with no deadline (kernel/thread/thread.c:956),
 *	so it is a wait with no way out. The pack makes one port never report.
 *
 *	Two pieces of evidence settle it. b21 cleared INIT_PURUPURU, so the rumble
 *	driver never initialised, and it still hung -- which exonerates the driver.
 *	And Max found that pulling the pack out *while hung* lets the boot continue,
 *	which is precisely a blocking wait releasing when the offending device leaves
 *	the bus.
 *
 *	WHY THIS FILE IS NO LONGER ONE LINE
 *
 *	The previous note here concluded that bounding the wait was not available to
 *	us, because `maple_wait_scan` is gated on INIT_MAPLE_ALL alongside
 *	`maple_init` itself, so clearing the flag would take the controller too.
 *
 *	That is true of the flag and false of the mechanism. INIT_MAPLE_ALL is the OR
 *	of eight peripheral flags and the gate is a bitwise AND, so no combination of
 *	flags separates the scan from the driver. But KOS_INIT_FLAGS() does nothing
 *	except *define variables*: for each subsystem it emits
 *
 *	    void (*func##_weak)(void) = ((flags) & (mask)) ? func : NULL;
 *
 *	and init.c later calls whatever the pointer holds. So the list below is
 *	KOS's own, generated from arch/init_flags.h and kos/init.h so it cannot
 *	drift, with exactly one line omitted -- and `maple_wait_scan_weak` defined
 *	NULL by hand instead. Every other subsystem, INIT_PURUPURU included, starts
 *	exactly as before.
 *
 *	WHAT REPLACES THE WAIT
 *
 *	`dc_maple_wait_scan_bounded` waits on exactly the condition KOS waits on, with
 *	a deadline. A normal boot is therefore unchanged -- the scan finishes in a few
 *	frames and the wait returns -- while a device that never reports costs the
 *	timeout rather than the console.
 *
 *	Regenerate the list with tools/gen-maple-flags.py after a KOS update.
 */

