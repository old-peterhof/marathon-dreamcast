/*
 *	The one line KOS would have emitted, inverted. `maple_wait_scan` is never
 *	called, so init never blocks on all four ports reporting.
 */
void (*maple_wait_scan_weak)(void) = NULL;

/*
 *	Bounded replacement for the scan wait.
 *
 *	The same predicate KOS uses -- `maple_state.scan_ready_mask == 0xf`, all four
 *	ports reported -- with a deadline on it. `maple_state` and the mask are both
 *	public in dc/maple.h, so this is KOS's own condition rather than a guess at
 *	one.
 *
 *	A normal boot leaves in a few frames and behaves exactly as it did before. A
 *	device that never answers costs the timeout instead of the console.
 *
 *	Returns 1 if the scan completed, 0 if it timed out. Neither is fatal: the mask
 *	falling short only means some port is unaccounted for, and the ports that did
 *	answer have already attached their devices.
 */
int dc_maple_wait_scan_bounded(unsigned int timeout_ms) {
	uint64_t deadline = timer_ms_gettime64() + timeout_ms;

	while (maple_state.scan_ready_mask != 0xf) {
		if (timer_ms_gettime64() >= deadline)
			return 0;

		/* Devices attach from the vblank handler, so yield rather than spin. */
		thd_pass();
	}

	return 1;
}
